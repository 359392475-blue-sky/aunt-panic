"""安全过滤器 —— 仅拦截政治类内容。

设计哲学（v0.4 大幅简化）：
==========================================
家族群里 90% 的谣言是医药/养生/健康类——这恰恰是项目核心反讽对象，
拦了就没法用。所以本版本**只保留政治拦截**，其他放行。

仍拦截的：
- 国家领导人姓名 / 党政敏感事件 / 仿冒官方机构发文
  → 反讽这类有合规风险，不可触碰

不再拦截的（之前 v0.3 拦的，本版放行）：
- 具名药品 / 保健品（片仔癀/阿胶/虫草等）
- 金融具体产品
- 色情暴力
- 一切"养生修辞"（根治/抗癌/排毒/提高免疫力 等）
"""

from dataclasses import dataclass
from typing import Optional


@dataclass
class 拦截结果:
    放行: bool
    原因: str = ""
    元反讽模板: Optional[str] = None


# ============================================================
# 词库 —— 仅政治
# ============================================================

政治高危词 = {
    # 现任 / 前任党和国家领导人
    "习近平", "李强", "王沪宁", "赵乐际", "蔡奇", "丁薛祥", "李希",
    "毛泽东", "邓小平", "江泽民", "胡锦涛", "温家宝", "李克强",
    # 党政敏感事件
    "六四", "天安门事件", "新疆", "西藏", "港独", "台独",
    "法轮功", "活摘", "文革", "大跃进", "三年困难",
    # 仿冒官方机构发文（标题/正文不许用这种话术）
    "国务院通知", "中央通知", "新华社快讯", "中央政法委通告",
    "中纪委通报", "国务院紧急", "中央紧急",
}

_元反讽模板_政治 = (
    "【元层次提醒】\n"
    "凡是冒充\"国务院通知\"\"新华社快讯\"\"中央紧急通告\"的群聊消息，"
    "99% 是假的。\n\n"
    "请直接去政府官网（gov.cn）或央媒 APP 核实。"
)

# 标题党词（生成阶段清洗用，不在源文检测中拦截）
标题党词 = {
    "震惊", "惊呆", "惊爆", "揭秘", "曝光", "内幕", "爆料",
    "紧急", "速看", "火速", "马上删", "看完即删", "扩散", "必看",
    "一定", "绝对", "100%", "唯一", "千万别",
    "竟然", "居然", "没想到", "想不到", "不看后悔",
    "刚刚发布", "刚刚宣布",
    "不转不是中国人", "是中国人就转", "有良心的都转",
}


# ============================================================
# 主入口
# ============================================================

def 判定(原文标题: str, 原文正文: str) -> 拦截结果:
    """返回是否放行。仅政治类拦截，其他全部放行。"""
    全文 = f"{原文标题}\n{原文正文}"
    for w in 政治高危词:
        if w in 全文:
            return 拦截结果(False, f"涉政高危词: {w}", _元反讽模板_政治)
    return 拦截结果(放行=True)


def 清洗标题(标题: str) -> str:
    """生成后清洗：把标题党词替换为中性表达，避免被微信秒驳。"""
    映射 = {
        "震惊": "提醒",
        "惊呆": "需注意",
        "惊爆": "披露",
        "紧急": "近期",
        "速看": "请阅",
        "火速": "尽快",
        "千万别": "建议不要",
        "100%": "高比例",
        "绝对": "明显",
        "刚刚发布": "近日发布",
    }
    for 旧, 新 in 映射.items():
        标题 = 标题.replace(旧, 新)
    return 标题
