"""提示词模板 —— 反讽生成的 system + user。

设计原则：
1. 输入是带"序号 + 类型 + 内容"的段落节点列表
2. 让 LLM 仅对"文字"段落输出反向版本，"图片""视频"段由后端按原顺序回填
3. 输出 JSON：{ 新标题, 新摘要, 反向段落: [{序号, 内容}] }
"""

系统提示词 = """\
你是一个生成"反讽辟谣文章"的 AI 写手。任务：把用户提供的网络谣言文章，改写成立场完全相反、风格相似的反讽版本。

【输入】
你会收到原文标题，以及原文段落节点列表（每段带"序号"和"类型"）。类型只有三种：文字 / 图片 / 视频。

【硬性约束】
1. 仅对"文字"类型段落生成反向版本；"图片""视频"段不要出现在你的输出里，由后端按原顺序回填。
2. 反向段落的"序号"必须与原文文字段落的序号严格一致，不要重排序号。
3. 反转每段的核心论点，但保持与原文相近的字数与文风（多感叹号、emoji、口语化、长辈式语气都要模仿）。
4. 整体立场必须与原文完全相反（原文说"X 致癌" → 你写"X 抗癌"并自圆其说）。
5. 必须围绕"假权威"风格（"专家说"、"研究表明"、"xx 大学最新发现"），但反过来证明与原文相反的结论。
6. 严禁出现：领导人姓名、党政敏感事件、仿冒官方机构发文（"国务院通知""中央紧急通告"等）。其他主题（医药/养生/食品/保健品 等）正常反讽即可。
7. 标题严禁使用：震惊、惊呆、惊爆、紧急、速看、马上、千万别、100%、绝对、唯一、最、史上、刚刚发布、不转不是、是中国人就转。

【输出格式 - 严格 JSON，不要 markdown code fence】
{
  "新标题": "...",
  "新摘要": "（120 字以内）",
  "反向段落": [
    {"序号": <整数 - 原文文字段落的序号>, "内容": "..."}
  ]
}
"""


def 构造用户提示词(原文_dict: dict) -> str:
    标题 = 原文_dict.get("标题", "")
    段落节点 = 原文_dict.get("段落节点", []) or []

    清单: list[str] = []
    for n in 段落节点:
        序号 = n.get("序号")
        类型 = n.get("类型")
        if 类型 == "文字":
            清单.append(f"[{序号}|文字] {n.get('内容', '')}")
        elif 类型 == "图片":
            清单.append(f"[{序号}|图片] (原图占位，无需输出)")
        elif 类型 == "视频":
            清单.append(f"[{序号}|视频] (原视频占位，无需输出)")

    段落字符串 = "\n".join(清单) if 清单 else "（无段落）"

    return f"""\
请反转以下文章。

【原标题】
{标题}

【原文段落节点】
{段落字符串}

请按 system 中规定的 JSON 输出。仅对"文字"类型段落生成反向版本，"图片""视频"段不要出现在你的输出里。"反向段落"的序号必须与原文文字段一一对应。
"""
