"""风格分类器 —— 判定原文风格。

目前用关键词启发式，未来可换成小模型分类。
本期非关键路径，仅作为提示词的辅助参考字段。
"""

from enum import Enum


class 风格(str, Enum):
    严肃科普 = "严肃科普"
    爆款震惊 = "爆款震惊"
    长辈图文 = "长辈图文"


_严肃科普词 = ("研究", "实验", "教授", "院士", "期刊", "数据显示", "论文")
_爆款震惊词 = ("震惊", "惊呆", "紧急", "速看", "千万别", "马上删", "曝光")
_长辈图文词 = ("家人", "朋友", "转给", "记得转", "保健", "养生", "祖传")


def 判定(标题: str, 正文: str) -> 风格:
    全文 = f"{标题}\n{正文}"
    严肃 = sum(w in 全文 for w in _严肃科普词)
    爆款 = sum(w in 全文 for w in _爆款震惊词)
    长辈 = sum(w in 全文 for w in _长辈图文词)
    最大 = max(严肃, 爆款, 长辈)
    if 最大 == 0 or 最大 == 长辈:
        return 风格.长辈图文
    if 最大 == 爆款:
        return 风格.爆款震惊
    return 风格.严肃科普
